<?php

namespace Database\Seeders;

use App\Models\Harvest;
use App\Models\Shipment;
use App\Models\User;
use App\Services\Agriculture\CommodityProfileService;
use App\Services\AI\AnalysisSnapshotService;
use App\Services\AI\DecisionEngine;
use App\Services\Routing\FreshnessAwareRouteService;
use App\Services\Sustainability\FreightCarbonEstimateService;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;
use RuntimeException;

/**
 * AgriFlow competition demo dataset.
 *
 * IMPORTANT:
 * - This seeder is intentionally destructive for OPERATIONAL records.
 * - It deletes previous harvests, shipments, AI-analysis history, decision
 *   results, and Digital Twin history before creating a clean demo dataset.
 * - It DOES NOT delete users or commodity_profiles / scientific references.
 * - Risk, route score, readiness, carbon, recommendations, and snapshots are
 *   generated by the current AgriFlow engines; they are not hardcoded here.
 * - Records are synthetic demonstration data, not claims of real field trials.
 */
class CompetitionDemoSeeder extends Seeder
{
    public const DEMO_DATASET_VERSION = 'competition-demo-v1';

    public function run(): void
    {
        $user = User::query()->orderBy('id')->first();

        if (!$user) {
            throw new RuntimeException(
                'CompetitionDemoSeeder requires at least one existing user. Register/login once, then run the seeder again.'
            );
        }

        $profiles = app(CommodityProfileService::class);
        $engine = app(DecisionEngine::class);
        $routes = app(FreshnessAwareRouteService::class);
        $carbon = app(FreightCarbonEstimateService::class);
        $snapshots = app(AnalysisSnapshotService::class);

        $this->assertRequiredCommodityProfiles($profiles);

        $summaryRows = [];

        DB::transaction(function () use (
            $user,
            $engine,
            $routes,
            $carbon,
            $snapshots,
            &$summaryRows
        ): void {
            $this->clearOperationalData();

            foreach ($this->demoRecords() as $record) {
                $harvest = Harvest::create([
                    'user_id' => $user->id,
                    'commodity' => $record['commodity'],
                    'weight' => $record['weight_kg'],
                    'location' => $record['harvest_location'],
                    'harvest_date' => today()
                        ->addDays($record['harvest_day_offset'])
                        ->toDateString(),
                    'expiry_date' => today()
                        ->addDays($record['deadline_day_offset'])
                        ->toDateString(),
                ]);

                $carbonEstimate = $carbon->estimate(
                    (float) $record['weight_kg'],
                    (float) $record['distance_km']
                );

                // Completed records are first evaluated in their final active
                // state. Delivery then closes the lifecycle without generating
                // a new post-delivery intervention recommendation.
                $initialStatus = $record['completed']
                    ? $record['final_active_status']
                    : $record['status'];

                $shipment = Shipment::create([
                    'harvest_id' => $harvest->id,
                    'origin' => $record['origin'],
                    'destination' => $record['destination'],
                    'distance_km' => $record['distance_km'],
                    'duration_hours' => $record['duration_hours'],
                    'carbon_emission' => $carbonEstimate['estimated_kg'],
                    'route_score' => null,
                    'status' => $initialStatus,
                    'recorded_temperature_c' => $record['temperature_c'],
                    'recorded_relative_humidity_percent' => $record['rh_percent'],
                    'recorded_moisture_percent' => $record['moisture_percent'],
                    'condition_source' => $this->hasRecordedCondition($record)
                        ? 'manual_entry'
                        : null,
                    'condition_recorded_at' => $this->hasRecordedCondition($record)
                        ? now()->subHours($record['condition_age_hours'])
                        : null,
                    'origin_lat' => $record['origin_lat'],
                    'origin_lng' => $record['origin_lng'],
                    'destination_lat' => $record['destination_lat'],
                    'destination_lng' => $record['destination_lng'],
                    // No synthetic road polyline is fabricated. The stored
                    // distance/duration are demo logistics inputs, while live
                    // routing may resolve geometry through the configured provider.
                    'route_geometry' => null,
                ]);

                $shipment->load('harvest');

                $analysis = $engine->analyze($shipment);
                $routeDecision = $routes->assessCurrentRoute(
                    $shipment,
                    $analysis
                );

                $recommendations = $this->buildRecommendationText($analysis);

                if ($record['completed']) {
                    $deliveredAt = now()->subHours($record['delivered_hours_ago']);

                    $completionSnapshot = $snapshots->build(
                        $shipment,
                        $analysis,
                        $routeDecision,
                        'delivery_completion',
                        $deliveredAt
                    );

                    $snapshots->persist(
                        $shipment,
                        $analysis,
                        $recommendations,
                        $routeDecision,
                        'delivery_completion',
                        $deliveredAt,
                        $completionSnapshot
                    );

                    $shipment->update([
                        'status' => 'Delivered',
                        'delivered_at' => $deliveredAt,
                        'completion_snapshot' => $completionSnapshot,
                    ]);
                } else {
                    $snapshots->persist(
                        $shipment,
                        $analysis,
                        $recommendations,
                        $routeDecision,
                        'competition_demo_seed'
                    );
                }

                $summaryRows[] = [
                    $record['demo_role'],
                    $record['commodity'],
                    $record['completed'] ? 'Delivered' : $initialStatus,
                    ($analysis['risk_score'] ?? '—') . '/100',
                    $analysis['risk_severity'] ?? $analysis['risk_level'] ?? '—',
                    ($routeDecision['route_score'] ?? '—') . '/100',
                ];
            }
        });

        $this->command?->newLine();
        $this->command?->info(
            'AgriFlow competition demo dataset installed: ' . self::DEMO_DATASET_VERSION
        );
        $this->command?->warn(
            'Previous operational records were removed. Users and commodity_profiles were preserved.'
        );
        $this->command?->table(
            ['Demo role', 'Commodity', 'Status', 'Risk', 'Severity', 'Route'],
            $summaryRows
        );
        $this->command?->info(
            'Synthetic demo records only — do not present them as real field-trial outcomes.'
        );
    }

    private function clearOperationalData(): void
    {
        // Dependency order keeps this safe even when foreign-key cascades or
        // older local schemas differ slightly.
        foreach ([
            'digital_twin_comparison_sets',
            'digital_twin_scenarios',
            'decision_results',
            'ai_analyses',
            'shipments',
            'harvests',
        ] as $table) {
            if (Schema::hasTable($table)) {
                DB::table($table)->delete();
            }
        }
    }

    private function assertRequiredCommodityProfiles(
        CommodityProfileService $profiles
    ): void {
        $required = [
            'Brokoli',
            'Tomat',
            'Timun',
            'Bayam',
            'Kopi',
            'Jagung Pipilan Kering',
            'Beras',
            'Cabai',
        ];

        $missing = collect($required)
            ->filter(
                fn (string $commodity): bool =>
                    $profiles->findForCommodity($commodity) === null
            )
            ->values();

        if ($missing->isNotEmpty()) {
            throw new RuntimeException(
                'Missing commodity profiles: '
                . $missing->implode(', ')
                . '. Run: php artisan db:seed --class=CommodityProfileSeeder'
            );
        }
    }

    private function hasRecordedCondition(array $record): bool
    {
        return $record['temperature_c'] !== null
            || $record['rh_percent'] !== null
            || $record['moisture_percent'] !== null;
    }

    private function buildRecommendationText(array $analysis): string
    {
        $actionLines = collect($analysis['recommended_actions'] ?? [])
            ->map(
                static fn (array $action): string =>
                    '- ' . ($action['action'] ?? 'Review shipment')
            )
            ->filter()
            ->implode("\n");

        if ($actionLines === '') {
            $actionLines = '- ' . (
                $analysis['recommended_action']
                ?? 'Review shipment'
            );
        }

        $reason = $analysis['recommendation_reason']
            ?? 'Continue monitoring the shipment against its current operational constraints.';

        $outcome = $analysis['expected_outcome']
            ?? 'Preserve the current operational window and reassess when recorded conditions change.';

        return "Recommendations:\n{$actionLines}\n\n"
            . "Explanation:\n{$reason}\n\n"
            . "Conclusion:\n{$outcome}";
    }

